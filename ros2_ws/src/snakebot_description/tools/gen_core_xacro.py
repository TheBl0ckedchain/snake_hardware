"""Generate snakebot.urdf.xacro from the Fusion-exported world-frame meshes.

Fixes vs. the fusion2urdf export:
  * joint origins recomputed from the actual servo-horn centres in the meshes
    (the exporter placed joints 2-6 one segment off)
  * real masses (inertia from mesh geometry, uniform density, scaled to the weighed mass)
  * ROS REP-103 frame: x forward (toward the head), y left, z up
  * clean names, joint limits, Pi 5 + YDLIDAR G2 + laser frame
"""
import numpy as np, trimesh, math, os

HERE = os.path.dirname(os.path.abspath(__file__))
MESH_DIR = os.path.join(HERE, '..', 'meshes')
OUT = os.path.join(HERE, '..', 'urdf', 'snakebot_core.xacro')

# CAD world -> ROS base frame: head points along CAD +Y, so rotate -90 deg about Z
R = np.array([[0, 1, 0], [-1, 0, 0], [0, 0, 1]], float)
MM = 1e-3

links = ['base_link', 'seg1', 'seg2', 'seg3', 'seg4', 'seg5', 'tail']
mass = {'base_link': 0.110, 'seg1': 0.090, 'seg2': 0.090, 'seg3': 0.090,
        'seg4': 0.090, 'seg5': 0.090, 'tail': 0.070}


def circles(m, z, rmin, rmax):
    s = m.section(plane_origin=[0, 0, z], plane_normal=[0, 0, 1])
    out = []
    if s is None:
        return out
    for ent in s.discrete:
        pts = ent[:, :2]
        c = pts.mean(0)
        r = np.linalg.norm(pts - c, axis=1)
        if rmin < r.mean() < rmax and r.std() < 0.05 * r.mean():
            out.append((c[0], c[1], z))
    return out


meshes = {n: trimesh.load(os.path.join(MESH_DIR, n + '.stl')) for n in links}

# --- servo horn centre of each link that carries a servo (joint k sits on link k-1's horn)
horn = {}
for n in links[:-1]:
    f = []
    for z in np.arange(58, 66.01, 0.1):
        f += circles(meshes[n], z, 3.8, 4.2)
    f = np.array(f)
    horn[n] = np.array([np.median(f[:, 0]), np.median(f[:, 1]), f[:, 2].max()])  # top of horn

# joint world positions (mm). frame of child link = its joint position
P = {'base_link': np.zeros(3)}
for parent, child in zip(links[:-1], links[1:]):
    P[child] = horn[parent]

# --- inertials from geometry, scaled to real mass
inertial = {}
for n in links:
    m = meshes[n]
    com = m.center_mass                    # mm, world
    I_unit = m.moment_inertia / m.mass     # mm^2 per unit mass (about COM, world axes)
    I = I_unit * mass[n] * MM * MM         # kg m^2
    inertial[n] = (R @ ((com - P[n]) * MM), R @ I @ R.T)

# --- lidar mount disc on the head: 3x M3 holes -> circumcentre; plate top height
b = meshes['base_link']
holes = []
for e in b.section(plane_origin=[0, 0, 16], plane_normal=[0, 0, 1]).discrete:
    p = e[:, :2]; c = p.mean(0); r = np.linalg.norm(p - c, axis=1).mean()
    if 1.3 < r < 1.9:
        holes.append(c)
holes = np.array(holes)
A = np.c_[2 * holes, np.ones(len(holes))]; bb = (holes ** 2).sum(1)
sol = np.linalg.lstsq(A, bb, rcond=None)[0]
disc_c = sol[:2]
v = b.vertices
plate_top = v[(v[:, 1] > 60) & (v[:, 2] < 25)][:, 2].max()
lidar_mount = R @ (np.array([disc_c[0], disc_c[1], plate_top]) * MM)

# Pi 5 on top of the head hood
hood = v[(v[:, 2] > 80)]
pi_mount = R @ (np.array([hood[:, 0].mean(), (hood[:, 1].min() + hood[:, 1].max()) / 2, v[:, 2].max()]) * MM)


def f(x):
    return ' '.join(f'{a:.6f}' for a in x)


def inert_xml(n):
    c, I = inertial[n]
    return (f'    <inertial>\n      <origin xyz="{f(c)}" rpy="0 0 0"/>\n'
            f'      <mass value="${{m_{n}}}"/>\n'
            f'      <inertia ixx="{I[0,0]:.4e}" iyy="{I[1,1]:.4e}" izz="{I[2,2]:.4e}" '
            f'ixy="{I[0,1]:.4e}" ixz="{I[0,2]:.4e}" iyz="{I[1,2]:.4e}"/>\n    </inertial>\n')


def mesh_xml(n, tag):
    xyz = R @ (-P[n] * MM)
    return (f'    <{tag}>\n      <origin xyz="{f(xyz)}" rpy="0 0 ${{-pi/2}}"/>\n'
            f'      <geometry><mesh filename="file://$(find snakebot_description)/meshes/{n}.stl" scale="0.001 0.001 0.001"/></geometry>\n'
            + ('      <material name="${color_' + ('head' if n == 'base_link' else 'body') + '}"/>\n' if tag == 'visual' else '')
            + f'    </{tag}>\n')


out = []
w = out.append
w('<?xml version="1.0"?>\n<!-- AUTO-GENERATED by gen.py from the Fusion meshes. Edit snakebot.urdf.xacro for settings. -->\n')
w('<robot xmlns:xacro="http://www.ros.org/wiki/xacro">\n\n')
for n in links:
    w(f'  <link name="{n}">\n')
    w(inert_xml(n)); w(mesh_xml(n, 'visual')); w(mesh_xml(n, 'collision'))
    w('  </link>\n\n')
for k, (parent, child) in enumerate(zip(links[:-1], links[1:]), 1):
    o = R @ ((P[child] - P[parent]) * MM)
    w(f'  <joint name="joint{k}" type="revolute">\n    <parent link="{parent}"/>\n    <child link="{child}"/>\n'
      f'    <origin xyz="{f(o)}" rpy="0 0 0"/>\n    <axis xyz="0 0 1"/>\n'
      f'    <limit lower="${{-joint_limit}}" upper="${{joint_limit}}" effort="${{joint_effort}}" velocity="${{joint_velocity}}"/>\n'
      f'    <dynamics damping="${{joint_damping}}" friction="${{joint_friction}}"/>\n  </joint>\n\n')

# electronics
w(f'''  <!-- Raspberry Pi 5 (placed on top of the head hood; box approximation) -->
  <joint name="pi5_joint" type="fixed">
    <parent link="base_link"/>
    <child link="pi5"/>
    <origin xyz="{pi_mount[0]:.6f} {pi_mount[1]:.6f} {pi_mount[2] + 0.0085:.6f}" rpy="0 0 0"/>
  </joint>
  <link name="pi5">
    <inertial>
      <mass value="${{m_pi5}}"/>
      <inertia ixx="${{m_pi5*(0.056**2+0.017**2)/12}}" iyy="${{m_pi5*(0.085**2+0.017**2)/12}}" izz="${{m_pi5*(0.085**2+0.056**2)/12}}" ixy="0" ixz="0" iyz="0"/>
    </inertial>
    <visual>
      <geometry><box size="0.085 0.056 0.017"/></geometry>
      <material name="pcb_green"/>
    </visual>
  </link>

  <!-- YDLIDAR G2 on the round mount plate of the head -->
  <joint name="lidar_joint" type="fixed">
    <parent link="base_link"/>
    <child link="lidar"/>
    <origin xyz="{lidar_mount[0]:.6f} {lidar_mount[1]:.6f} {lidar_mount[2]:.6f}" rpy="0 0 0"/>
  </joint>
  <link name="lidar">
    <inertial>
      <origin xyz="0 0 ${{lidar_body_h/2}}"/>
      <mass value="${{m_lidar}}"/>
      <inertia ixx="${{m_lidar*(3*lidar_body_r**2+lidar_body_h**2)/12}}" iyy="${{m_lidar*(3*lidar_body_r**2+lidar_body_h**2)/12}}" izz="${{m_lidar*lidar_body_r**2/2}}" ixy="0" ixz="0" iyz="0"/>
    </inertial>
    <visual>
      <origin xyz="0 0 ${{lidar_body_h/2}}"/>
      <geometry><cylinder radius="${{lidar_body_r}}" length="${{lidar_body_h}}"/></geometry>
      <material name="black"/>
    </visual>
  </link>

  <!-- laser frame: scan plane. x = lidar zero angle (G2: direction of the cable outlet) -->
  <joint name="laser_joint" type="fixed">
    <parent link="lidar"/>
    <child link="laser"/>
    <origin xyz="0 0 ${{lidar_scan_height}}" rpy="0 0 ${{lidar_yaw}}"/>
  </joint>
  <link name="laser"/>

</robot>
''')

open(OUT, 'w').write(''.join(out))
print('horn centres (mm):'); [print(' ', k, np.round(v_, 2)) for k, v_ in horn.items()]
print('joint offsets (m):')
for k, (pa, ch) in enumerate(zip(links[:-1], links[1:]), 1):
    print(f'  joint{k}', np.round(R @ ((P[ch] - P[pa]) * MM), 5))
print('lidar disc centre mm', np.round(disc_c, 2), 'plate top', round(plate_top, 2), '-> base frame', np.round(lidar_mount, 4))
print('pi mount base frame', np.round(pi_mount, 4))
for n in links:
    c, I = inertial[n]; print(n, 'com', np.round(c, 4), 'diagI', np.round(np.diag(I), 7))
